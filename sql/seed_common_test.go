// TestSeedDefaultData_Agnostic verifies that SeedDefaultData populates any repository store implementation.
func TestSeedDefaultData_Agnostic(t *testing.T) {
	ctx := context.Background()
	store := memory.New()
	targetUserID := "seeded-user-1"

	if err := sql.SeedDefaultData(ctx, store, store, store, store, targetUserID); err != nil {
		t.Fatalf("SeedDefaultData failed: %v", err)
	}

	// 1. Verify profile
	prof, err := store.GetProfile(ctx, targetUserID)
	if err != nil {
		t.Fatalf("get seeded profile: %v", err)
	}
	if prof.UserID != targetUserID {
		t.Errorf("expected user %s, got %s", targetUserID, prof.UserID)
	}

	// 2. Verify presets
	presets, err := store.ListPresets(ctx, targetUserID)
	if err != nil {
		t.Fatalf("list presets: %v", err)
	}
	if len(presets) != 2 {
		t.Errorf("expected 2 seeded presets, got %d", len(presets))
	}

	// 3. Verify templates
	templates, err := store.ListTemplates(ctx, targetUserID)
	if err != nil {
		t.Fatalf("list templates: %v", err)
	}
	if len(templates) != 5 {
		t.Errorf("expected 5 templates, got %d", len(templates))
	}

	// 4. Verify branch and initial version
	branches, err := store.ListBranches(ctx, targetUserID)
	if err != nil {
		t.Fatalf("list branches: %v", err)
	}
	if len(branches) != 1 || !branches[0].IsDefault {
		t.Fatalf("expected 1 default branch, got %+v", branches)
	}
	if branches[0].ActiveVersionID == nil || *branches[0].ActiveVersionID == "" {
		t.Fatal("expected default branch to have an active version")
	}

	ver, err := store.GetVersion(ctx, branches[0].ID, *branches[0].ActiveVersionID)
	if err != nil {
		t.Fatalf("get active version: %v", err)
	}
	if ver.Status != domain.VersionStatusCompleted {
		t.Errorf("expected completed version, got %s", ver.Status)
	}
}

